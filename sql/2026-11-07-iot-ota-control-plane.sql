-- IoT control-plane schema for device authentication, configuration, telemetry, and HTTPS OTA.
-- This script is idempotent and targets the PostgreSQL application database.

CREATE TABLE IF NOT EXISTS "IotDeviceAgent" (
    "Id" uuid PRIMARY KEY,
    "DeviceId" varchar(128) NOT NULL,
    "Name" varchar(200) NOT NULL,
    "DeviceType" varchar(64) NOT NULL,
    "Platform" varchar(64) NOT NULL,
    "BoardType" varchar(128) NOT NULL,
    "BoardRevision" varchar(128) NOT NULL,
    "Location" varchar(200) NOT NULL,
    "Description" text NULL,
    "Status" varchar(32) NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT true,
    "LastSeenAt" timestamptz NULL,
    "LastDeviceTimestamp" timestamptz NULL,
    "LastFirmwareVersion" varchar(128) NULL,
    "LastIpAddress" varchar(64) NULL,
    "LastRssi" integer NULL,
    "LastUptimeSeconds" bigint NULL,
    "CapabilitiesJson" jsonb NULL,
    "CreatedAt" timestamptz NOT NULL,
    "UpdatedAt" timestamptz NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotDeviceAgent_DeviceId"
    ON "IotDeviceAgent" ("DeviceId");

CREATE TABLE IF NOT EXISTS "IotDeviceCredential" (
    "Id" uuid PRIMARY KEY,
    "DeviceAgentId" uuid NOT NULL,
    "KeyPrefix" varchar(32) NOT NULL,
    "Salt" bytea NOT NULL,
    "KeyHash" bytea NOT NULL,
    "CreatedAt" timestamptz NOT NULL,
    "RevokedAt" timestamptz NULL,
    CONSTRAINT "FK_IotDeviceCredential_IotDeviceAgent"
        FOREIGN KEY ("DeviceAgentId") REFERENCES "IotDeviceAgent" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotDeviceCredential_KeyPrefix"
    ON "IotDeviceCredential" ("KeyPrefix");

CREATE INDEX IF NOT EXISTS "IX_IotDeviceCredential_DeviceAgentId"
    ON "IotDeviceCredential" ("DeviceAgentId");

CREATE TABLE IF NOT EXISTS "IotDeviceReport" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceAgentId" uuid NOT NULL,
    "Kind" varchar(32) NOT NULL,
    "DeviceTimestamp" timestamptz NOT NULL,
    "ReceivedAt" timestamptz NOT NULL,
    "FirmwareVersion" varchar(128) NOT NULL,
    "PayloadJson" jsonb NOT NULL,
    "PayloadHash" varchar(128) NOT NULL,
    CONSTRAINT "FK_IotDeviceReport_IotDeviceAgent"
        FOREIGN KEY ("DeviceAgentId") REFERENCES "IotDeviceAgent" ("Id") ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS "IX_IotDeviceReport_DeviceAgentId_DeviceTimestamp"
    ON "IotDeviceReport" ("DeviceAgentId", "DeviceTimestamp");

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotDeviceReport_Dedup"
    ON "IotDeviceReport" ("DeviceAgentId", "DeviceTimestamp", "PayloadHash");

CREATE TABLE IF NOT EXISTS "IotSensorType" (
    "Id" uuid PRIMARY KEY,
    "Code" varchar(64) NOT NULL,
    "Name" varchar(128) NOT NULL,
    "Model" varchar(128) NULL,
    "Protocol" varchar(64) NOT NULL,
    "Unit" varchar(64) NOT NULL,
    "ParametersJson" jsonb NOT NULL,
    "PinRequirementsJson" jsonb NOT NULL,
    "DriverKey" varchar(128) NOT NULL,
    "IsActive" boolean NOT NULL DEFAULT true,
    "CreatedAt" timestamptz NOT NULL,
    "UpdatedAt" timestamptz NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotSensorType_Code"
    ON "IotSensorType" ("Code");

CREATE TABLE IF NOT EXISTS "IotDeviceSensor" (
    "Id" uuid PRIMARY KEY,
    "DeviceAgentId" uuid NOT NULL,
    "SensorTypeId" uuid NOT NULL,
    "Label" varchar(128) NOT NULL,
    "Protocol" varchar(64) NOT NULL,
    "Unit" varchar(64) NOT NULL,
    "PinMappingsJson" jsonb NOT NULL,
    "ReadIntervalSeconds" integer NOT NULL,
    "CalibrationJson" jsonb NULL,
    "IsEnabled" boolean NOT NULL DEFAULT true,
    "CreatedAt" timestamptz NOT NULL,
    "UpdatedAt" timestamptz NOT NULL,
    CONSTRAINT "FK_IotDeviceSensor_IotDeviceAgent"
        FOREIGN KEY ("DeviceAgentId") REFERENCES "IotDeviceAgent" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_IotDeviceSensor_IotSensorType"
        FOREIGN KEY ("SensorTypeId") REFERENCES "IotSensorType" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotDeviceSensor_DeviceAgentId_Label"
    ON "IotDeviceSensor" ("DeviceAgentId", "Label");

CREATE TABLE IF NOT EXISTS "IotDeviceConfiguration" (
    "Id" uuid PRIMARY KEY,
    "DeviceAgentId" uuid NOT NULL,
    "DesiredVersion" integer NOT NULL,
    "DesiredJson" jsonb NOT NULL,
    "DesiredStatus" varchar(32) NOT NULL,
    "DesiredUpdatedAt" timestamptz NOT NULL,
    "ReportedVersion" integer NULL,
    "ReportedJson" jsonb NULL,
    "ReportedStatus" varchar(32) NULL,
    "ReportedAt" timestamptz NULL,
    "RejectionReason" varchar(2000) NULL,
    CONSTRAINT "FK_IotDeviceConfiguration_IotDeviceAgent"
        FOREIGN KEY ("DeviceAgentId") REFERENCES "IotDeviceAgent" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotDeviceConfiguration_DeviceAgentId"
    ON "IotDeviceConfiguration" ("DeviceAgentId");

CREATE TABLE IF NOT EXISTS "IotFirmwarePackage" (
    "Id" uuid PRIMARY KEY,
    "PackageName" varchar(200) NOT NULL,
    "Version" varchar(128) NOT NULL,
    "TargetMcu" varchar(64) NOT NULL,
    "CompatibleBoardProfilesJson" jsonb NOT NULL,
    "CompatibleHardwareRevisionsJson" jsonb NOT NULL,
    "Notes" text NULL,
    "FileName" varchar(255) NOT NULL,
    "StoragePath" varchar(500) NOT NULL,
    "SizeBytes" bigint NOT NULL CHECK ("SizeBytes" >= 0),
    "Sha256" varchar(128) NOT NULL,
    "SignatureStatus" varchar(32) NOT NULL,
    "CreatedAt" timestamptz NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotFirmwarePackage_TargetMcu_Version"
    ON "IotFirmwarePackage" ("TargetMcu", "Version");

CREATE TABLE IF NOT EXISTS "IotOtaJob" (
    "Id" uuid PRIMARY KEY,
    "DeviceAgentId" uuid NOT NULL,
    "FirmwarePackageId" uuid NOT NULL,
    "Status" varchar(32) NOT NULL,
    "Progress" integer NOT NULL CHECK ("Progress" BETWEEN 0 AND 100),
    "FailureReason" varchar(2000) NULL,
    "CurrentFirmwareVersion" varchar(128) NULL,
    "ReportedFirmwareVersion" varchar(128) NULL,
    "RequestedAt" timestamptz NOT NULL,
    "LastActivityAt" timestamptz NOT NULL,
    "ConfirmedAt" timestamptz NULL,
    CONSTRAINT "FK_IotOtaJob_IotDeviceAgent"
        FOREIGN KEY ("DeviceAgentId") REFERENCES "IotDeviceAgent" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_IotOtaJob_IotFirmwarePackage"
        FOREIGN KEY ("FirmwarePackageId") REFERENCES "IotFirmwarePackage" ("Id") ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS "IX_IotOtaJob_DeviceAgentId_Status"
    ON "IotOtaJob" ("DeviceAgentId", "Status");

CREATE TABLE IF NOT EXISTS "IotOtaEvent" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "OtaJobId" uuid NOT NULL,
    "Sequence" integer NOT NULL,
    "EventType" varchar(32) NOT NULL,
    "Progress" integer NOT NULL CHECK ("Progress" BETWEEN 0 AND 100),
    "Message" varchar(2000) NULL,
    "ReportedFirmwareVersion" varchar(128) NULL,
    "OccurredAt" timestamptz NOT NULL,
    "ReceivedAt" timestamptz NOT NULL,
    CONSTRAINT "FK_IotOtaEvent_IotOtaJob"
        FOREIGN KEY ("OtaJobId") REFERENCES "IotOtaJob" ("Id") ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_IotOtaEvent_OtaJobId_Sequence"
    ON "IotOtaEvent" ("OtaJobId", "Sequence");

CREATE TABLE IF NOT EXISTS "IotActivityEvent" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DeviceAgentId" uuid NULL,
    "EventType" varchar(64) NOT NULL,
    "Message" varchar(2000) NOT NULL,
    "DetailsJson" jsonb NULL,
    "OccurredAt" timestamptz NOT NULL,
    CONSTRAINT "FK_IotActivityEvent_IotDeviceAgent"
        FOREIGN KEY ("DeviceAgentId") REFERENCES "IotDeviceAgent" ("Id") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "IX_IotActivityEvent_DeviceAgentId_OccurredAt"
    ON "IotActivityEvent" ("DeviceAgentId", "OccurredAt");
