-- =========================================================
-- 2. QcInspection — satu tabel transaksi utama untuk semua form
-- =========================================================
CREATE TABLE IF NOT EXISTS "QcInspection" (
    "Id"                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InspectionNo"         varchar(50) NULL,
    "FormId"               int         NOT NULL,
    "InspectionDate"       date        NOT NULL,

    -- Referensi Company (PKBPayroll, cross-db, tanpa FK constraint).
    "CompanyId"            int         NULL,
    "CompanyNameSnapshot"  varchar(200) NULL,

    -- Lokasi — snapshot dari MyPAD/RSUPPKB agar histori tetap terbaca.
    "WilayahKode"          varchar(50)  NULL,
    "PersilSumber"         varchar(20)  NULL,  -- KLP / TNM_NNS / LHN_NNS / PNN
    "PersilId"             varchar(100) NULL,
    "PersilKode"           varchar(100) NULL,
    "KodeAfdeling"         varchar(50)  NULL,

    "Commodity"            varchar(32)  NOT NULL,
    "PeriodMonth"          int          NULL CHECK ("PeriodMonth" BETWEEN 1 AND 12),
    "PeriodYear"           int          NULL,

    -- Status & approval.
    "Status"               varchar(32)  NOT NULL DEFAULT 'DRAFT',
    "CurrentApprovalLevel" int          NOT NULL DEFAULT 0,

    -- Field spesifik per form (hibrida). Field filter/dashboard tetap kolom di atas.
    "DataJson"             jsonb        NULL,

    "CreatedBy"            varchar(100) NULL,
    "CreatedAt"            timestamptz  NOT NULL DEFAULT now(),
    "UpdatedBy"            varchar(100) NULL,
    "UpdatedAt"            timestamptz  NULL,
    "SubmittedAt"          timestamptz  NULL,
    "ApprovedAt"           timestamptz  NULL,  -- diisi saat final approval, BUKAN saat CLOSE
    "ClosedAt"             timestamptz  NULL,

    CONSTRAINT "FK_QcInspection_QcForm"
        FOREIGN KEY ("FormId") REFERENCES "QcForm" ("Id") ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_QcInspection_InspectionNo"
    ON "QcInspection" ("InspectionNo")
    WHERE "InspectionNo" IS NOT NULL;

CREATE INDEX IF NOT EXISTS "IX_QcInspection_FormId"
    ON "QcInspection" ("FormId");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_Status"
    ON "QcInspection" ("Status");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_CompanyId"
    ON "QcInspection" ("CompanyId");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_WilayahKode"
    ON "QcInspection" ("WilayahKode");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_Commodity"
    ON "QcInspection" ("Commodity");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_InspectionDate"
    ON "QcInspection" ("InspectionDate");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_PeriodYear_PeriodMonth"
    ON "QcInspection" ("PeriodYear", "PeriodMonth");

CREATE INDEX IF NOT EXISTS "IX_QcInspection_Status_CurrentApprovalLevel"
    ON "QcInspection" ("Status", "CurrentApprovalLevel");


-- =========================================================
-- 3. QcApproval — satu row per (InspectionId, Level) = current state
-- =========================================================
CREATE TABLE IF NOT EXISTS "QcApproval" (
    "Id"                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InspectionId"         bigint      NOT NULL,
    "Level"                int         NOT NULL,

    "ApproverUserId"       int         NULL,     -- FK → UtlUser (SET NULL bila user dihapus)
    "ApproverNameSnapshot" varchar(150) NULL,
    "ApproverGroupId"      int         NULL,     -- FK → UtlGroup (SET NULL)

    -- APPROVE / REJECT / REQUEST_REVISION (kosong saat PENDING).
    "Action"               varchar(32) NOT NULL DEFAULT '',
    -- PENDING / APPROVED / REJECTED / REVISION_REQUIRED
    "Status"               varchar(32) NOT NULL DEFAULT 'PENDING',

    "Comment"              text        NULL,
    "ApprovedAt"           timestamptz NULL,
    "CreatedAt"            timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt"            timestamptz NULL,

    CONSTRAINT "FK_QcApproval_QcInspection"
        FOREIGN KEY ("InspectionId") REFERENCES "QcInspection" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_QcApproval_UtlUser"
        FOREIGN KEY ("ApproverUserId") REFERENCES "UtlUser" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_QcApproval_UtlGroup"
        FOREIGN KEY ("ApproverGroupId") REFERENCES "UtlGroup" ("Id") ON DELETE SET NULL
);

-- UNIQUE: satu row per (inspeksi, level). Current state approval; histori di QcHistory.
CREATE UNIQUE INDEX IF NOT EXISTS "IX_QcApproval_InspectionId_Level"
    ON "QcApproval" ("InspectionId", "Level");

CREATE INDEX IF NOT EXISTS "IX_QcApproval_Status"
    ON "QcApproval" ("Status");


-- =========================================================
-- 4. QcFinding — temuan, one-to-many per inspeksi
-- =========================================================
CREATE TABLE IF NOT EXISTS "QcFinding" (
    "Id"               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FindingNo"        varchar(50) NULL,
    "InspectionId"     bigint      NOT NULL,

    "Category"         varchar(100) NULL,
    "Description"      text         NOT NULL,
    -- MINOR / MAJOR / CRITICAL
    "Severity"         varchar(32)  NOT NULL DEFAULT 'MINOR',

    "PicUserId"        int          NULL,
    "PicNameSnapshot"  varchar(150) NULL,
    "TargetDate"       date         NULL,

    -- OPEN / FOLLOW_UP / WAITING_VERIFICATION / VERIFIED / CLOSED
    "Status"           varchar(32)  NOT NULL DEFAULT 'OPEN',
    "FollowUpNote"     text         NULL,

    "VerifiedByUserId" int          NULL,
    "VerifiedDate"     date         NULL,

    "CreatedBy"        varchar(100) NULL,
    "CreatedAt"        timestamptz  NOT NULL DEFAULT now(),
    "UpdatedBy"        varchar(100) NULL,
    "UpdatedAt"        timestamptz  NULL,

    CONSTRAINT "FK_QcFinding_QcInspection"
        FOREIGN KEY ("InspectionId") REFERENCES "QcInspection" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_QcFinding_PicUser"
        FOREIGN KEY ("PicUserId") REFERENCES "UtlUser" ("Id") ON DELETE SET NULL,
    CONSTRAINT "FK_QcFinding_VerifiedBy"
        FOREIGN KEY ("VerifiedByUserId") REFERENCES "UtlUser" ("Id") ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_QcFinding_FindingNo"
    ON "QcFinding" ("FindingNo")
    WHERE "FindingNo" IS NOT NULL;

CREATE INDEX IF NOT EXISTS "IX_QcFinding_InspectionId"
    ON "QcFinding" ("InspectionId");

CREATE INDEX IF NOT EXISTS "IX_QcFinding_Status"
    ON "QcFinding" ("Status");

CREATE INDEX IF NOT EXISTS "IX_QcFinding_TargetDate"
    ON "QcFinding" ("TargetDate");

CREATE INDEX IF NOT EXISTS "IX_QcFinding_Severity"
    ON "QcFinding" ("Severity");


-- =========================================================
-- 5. QcHistory — audit trail immutable (RESTRICT)
-- =========================================================
CREATE TABLE IF NOT EXISTS "QcHistory" (
    "Id"            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InspectionId"  bigint      NOT NULL,

    "UserId"        int         NULL,
    -- CREATE / UPDATE / SUBMIT / APPROVE / REJECT / REQUEST_REVISION / RESUBMIT / CLOSE
    "Action"        varchar(32) NOT NULL,
    "FromStatus"    varchar(32) NULL,
    "ToStatus"      varchar(32) NULL,
    "ApprovalLevel" int         NULL,
    "Note"          text        NULL,

    "CreatedAt"     timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT "FK_QcHistory_QcInspection"
        FOREIGN KEY ("InspectionId") REFERENCES "QcInspection" ("Id") ON DELETE RESTRICT,
    CONSTRAINT "FK_QcHistory_UtlUser"
        FOREIGN KEY ("UserId") REFERENCES "UtlUser" ("Id") ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS "IX_QcHistory_InspectionId_CreatedAt"
    ON "QcHistory" ("InspectionId", "CreatedAt");


