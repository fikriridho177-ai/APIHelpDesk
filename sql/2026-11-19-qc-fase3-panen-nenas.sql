-- Target database : helpdeskasd (PostgreSQL). Jalankan MANUAL setelah review.
-- Idempotent: CREATE TABLE/INDEX IF NOT EXISTS, CREATE OR REPLACE VIEW,
--             UPDATE aktivasi form (tanpa menimpa metadata lain).
-- Script ini TANPA BEGIN/COMMIT internal supaya bisa dibungkus transaksi uji.
-- Rollback: 2026-11-19-qc-fase3-panen-nenas-rollback.sql
--
-- Angka MENTAH saja di tabel (jumlah pohon & butir buah). Total, buah
-- tertinggal, dan % dihitung di view PostgreSQL — tidak disimpan.
-- Asumsi rumus (template Excel kosong tanpa formula, lihat docs/qc/03-panen-nenas.md):
--   TotalBuah        = BuahTidakDipetik + BuahTelahDipetik + BuahTerpotong
--   BuahTertinggal   = BuahTidakDipetik + BuahTerpotong
--   PersenTertinggal = BuahTertinggal / TotalBuah * 100 (NULL bila TotalBuah = 0)

-- =========================================================
-- 1. TrnQcInspSampelPanenNenas — satu baris per jalur sampel
--    Kapasitas 20 baris sesuai template 12.PANEN NENAS.xls (sheet PNN NNS).
-- =========================================================
CREATE TABLE IF NOT EXISTS "TrnQcInspSampelPanenNenas" (
    "Id"                bigint       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InspectionId"      bigint       NOT NULL,
    "RowNo"             int          NOT NULL,
    "NomorJalur"        varchar(50)  NOT NULL,
    "JumlahPohon"       int          NOT NULL DEFAULT 0,
    "BuahTidakDipetik"  int          NOT NULL DEFAULT 0,
    "BuahTelahDipetik"  int          NOT NULL DEFAULT 0,
    "BuahTerpotong"     int          NOT NULL DEFAULT 0,
    "Keterangan"        varchar(250) NULL,
    "CreatedAt"         timestamptz  NOT NULL DEFAULT now(),
    CONSTRAINT "FK_TrnQcInspSampelPanenNenas_TrnQcInspection"
        FOREIGN KEY ("InspectionId") REFERENCES "TrnQcInspection" ("Id") ON DELETE CASCADE,
    CONSTRAINT "CK_TrnQcInspSampelPanenNenas_RowNo" CHECK ("RowNo" BETWEEN 1 AND 20),
    CONSTRAINT "CK_TrnQcInspSampelPanenNenas_JumlahPohon" CHECK ("JumlahPohon" >= 0),
    CONSTRAINT "CK_TrnQcInspSampelPanenNenas_BuahTidakDipetik" CHECK ("BuahTidakDipetik" >= 0),
    CONSTRAINT "CK_TrnQcInspSampelPanenNenas_BuahTelahDipetik" CHECK ("BuahTelahDipetik" >= 0),
    CONSTRAINT "CK_TrnQcInspSampelPanenNenas_BuahTerpotong" CHECK ("BuahTerpotong" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_TrnQcInspSampelPanenNenas_InspectionId_RowNo"
    ON "TrnQcInspSampelPanenNenas" ("InspectionId", "RowNo");

-- =========================================================
-- 2. View hitungan per baris (dipakai export & monitoring)
-- =========================================================
CREATE OR REPLACE VIEW "vwQcPanenNenasDetail" AS
SELECT
    s."Id",
    s."InspectionId",
    s."RowNo",
    s."NomorJalur",
    s."JumlahPohon",
    s."BuahTidakDipetik",
    s."BuahTelahDipetik",
    s."BuahTerpotong",
    s."Keterangan",
    (s."BuahTidakDipetik" + s."BuahTelahDipetik" + s."BuahTerpotong") AS "TotalBuah",
    (s."BuahTidakDipetik" + s."BuahTerpotong") AS "BuahTertinggal",
    CASE WHEN (s."BuahTidakDipetik" + s."BuahTelahDipetik" + s."BuahTerpotong") > 0
        THEN ROUND(
            (s."BuahTidakDipetik" + s."BuahTerpotong")::numeric * 100
            / (s."BuahTidakDipetik" + s."BuahTelahDipetik" + s."BuahTerpotong"), 2)
        ELSE NULL
    END AS "PersenTertinggal",
    i."InspectionNo",
    i."FormId",
    i."InspectionDate",
    i."CompanyId",
    i."CompanyNameSnapshot",
    i."WilayahKode",
    i."KodeAfdeling",
    i."PersilSumber",
    i."PersilKode",
    i."PeriodMonth",
    i."PeriodYear",
    i."Status",
    i."Revision"
FROM "TrnQcInspSampelPanenNenas" s
JOIN "TrnQcInspection" i ON i."Id" = s."InspectionId";

-- =========================================================
-- 3. View rekap per inspeksi (footer Total & % template)
-- =========================================================
CREATE OR REPLACE VIEW "vwQcPanenNenasRekap" AS
SELECT
    i."Id" AS "InspectionId",
    i."InspectionNo",
    i."FormId",
    i."InspectionDate",
    i."CompanyId",
    i."CompanyNameSnapshot",
    i."WilayahKode",
    i."KodeAfdeling",
    i."PersilSumber",
    i."PersilKode",
    i."PeriodMonth",
    i."PeriodYear",
    i."Status",
    i."Revision",
    COUNT(s."Id")::int AS "JumlahSampel",
    COALESCE(SUM(s."JumlahPohon"), 0)::int AS "TotalPohon",
    COALESCE(SUM(s."BuahTidakDipetik"), 0)::int AS "TotalBuahTidakDipetik",
    COALESCE(SUM(s."BuahTelahDipetik"), 0)::int AS "TotalBuahTelahDipetik",
    COALESCE(SUM(s."BuahTerpotong"), 0)::int AS "TotalBuahTerpotong",
    COALESCE(SUM(s."BuahTidakDipetik" + s."BuahTelahDipetik" + s."BuahTerpotong"), 0)::int AS "TotalBuah",
    COALESCE(SUM(s."BuahTidakDipetik" + s."BuahTerpotong"), 0)::int AS "TotalBuahTertinggal",
    CASE WHEN COALESCE(SUM(s."BuahTidakDipetik" + s."BuahTelahDipetik" + s."BuahTerpotong"), 0) > 0
        THEN ROUND(
            SUM(s."BuahTidakDipetik" + s."BuahTerpotong")::numeric * 100
            / SUM(s."BuahTidakDipetik" + s."BuahTelahDipetik" + s."BuahTerpotong"), 2)
        ELSE NULL
    END AS "PersenTertinggal"
FROM "TrnQcInspection" i
JOIN "MstQcForm" f ON f."Id" = i."FormId" AND f."Code" = 'QC-PANEN-NNS'
LEFT JOIN "TrnQcInspSampelPanenNenas" s ON s."InspectionId" = i."Id"
GROUP BY i."Id", i."InspectionNo", i."FormId", i."InspectionDate", i."CompanyId",
         i."CompanyNameSnapshot", i."WilayahKode", i."KodeAfdeling", i."PersilSumber",
         i."PersilKode", i."PeriodMonth", i."PeriodYear", i."Status", i."Revision";

-- =========================================================
-- 4. Aktifkan form Panen Nenas (grid input tersedia mulai Fase 3).
--    Alur approval 4 level sudah di-seed Fase 1 untuk semua form.
-- =========================================================
UPDATE "MstQcForm" SET "Active" = true WHERE "Code" = 'QC-PANEN-NNS';