-- Jalankan manual sebelum deploy API. Tidak menyisipkan data master atau izin.
BEGIN;
CREATE TABLE IF NOT EXISTS "WadObject" (
    "Id" serial PRIMARY KEY,
    "Module" varchar(20) NOT NULL,
    "Code" varchar(50) NOT NULL,
    "Name" varchar(200) NOT NULL,
    "ObjectType" varchar(50) NOT NULL,
    "Wilayah" varchar(100) NOT NULL,
    "Location" varchar(200),
    "ReferenceValueCm" numeric(14,3),
    "AreaHa" numeric(12,4),
    "PicName" varchar(150),
    "StartDate" date,
    "TargetDate" date,
    "TargetQty" numeric(14,3),
    "Unit" varchar(30),
    "Active" boolean NOT NULL DEFAULT true,
    "SortOrder" integer NOT NULL DEFAULT 0,
    "CreatedAt" timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE "WadObject" ADD COLUMN IF NOT EXISTS "IsDemo" boolean NOT NULL DEFAULT false;
ALTER TABLE "WadObject" ADD COLUMN IF NOT EXISTS "MeasurementMethod" varchar(30);
ALTER TABLE "WadObject" ADD COLUMN IF NOT EXISTS "VerifyDropCm" numeric(14,3);
ALTER TABLE "WadObject" ADD COLUMN IF NOT EXISTS "CriticalDropCm" numeric(14,3);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_WadObject_Module_Code" ON "WadObject" ("Module", "Code");
CREATE INDEX IF NOT EXISTS "IX_WadObject_Module" ON "WadObject" ("Module");

CREATE TABLE IF NOT EXISTS "WadReport" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ObjectId" integer NOT NULL REFERENCES "WadObject" ("Id") ON DELETE RESTRICT,
    "Module" varchar(20) NOT NULL,
    "ObservedDate" date NOT NULL,
    "ObservedTime" time,
    "Condition" varchar(30),
    "WaterLevelCm" numeric(10,2),
    "MeasurementValue" numeric(14,3),
    "MeasurementUnit" varchar(10),
    "MeasuredValueCm" numeric(14,3),
    "ReferenceValueCm" numeric(14,3),
    "DropCm" numeric(14,3),
    "FloodAreaHa" numeric(12,4),
    "FloodHeightCm" numeric(10,2),
    "FloodStartDate" date,
    "FloodDurationDays" integer,
    "WorkDescription" varchar(2000),
    "RealizationQty" numeric(14,3),
    "RealizationUnit" varchar(30),
    "ProgressPercent" integer,
    "Constraints" varchar(2000),
    "Notes" varchar(2000),
    "CreatedByUserId" integer NOT NULL,
    "CreatedByName" varchar(150) NOT NULL,
    "CreatedAt" timestamptz NOT NULL DEFAULT now(),
    "UpdatedAt" timestamptz,
    "UpdatedByUserId" integer
);
ALTER TABLE "WadReport" ADD COLUMN IF NOT EXISTS "RequestId" uuid;
ALTER TABLE "WadReport" ADD COLUMN IF NOT EXISTS "MeasurementMethod" varchar(30);
CREATE UNIQUE INDEX IF NOT EXISTS "IX_WadReport_CreatedByUserId_RequestId" ON "WadReport" ("CreatedByUserId", "RequestId");
CREATE INDEX IF NOT EXISTS "IX_WadReport_Module_ObservedDate" ON "WadReport" ("Module", "ObservedDate");
CREATE INDEX IF NOT EXISTS "IX_WadReport_ObjectId" ON "WadReport" ("ObjectId");

CREATE TABLE IF NOT EXISTS "WadReportPhoto" (
    "Id" bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ReportId" bigint NOT NULL REFERENCES "WadReport" ("Id") ON DELETE CASCADE,
    "FileUrl" varchar(500) NOT NULL,
    "Keterangan" varchar(200),
    "Phase" varchar(20),
    "SortOrder" integer NOT NULL DEFAULT 0,
    "CreatedAt" timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE "WadReportPhoto" ADD COLUMN IF NOT EXISTS "RequestId" uuid;
CREATE INDEX IF NOT EXISTS "IX_WadReportPhoto_ReportId" ON "WadReportPhoto" ("ReportId");
CREATE UNIQUE INDEX IF NOT EXISTS "IX_WadReportPhoto_ReportId_RequestId" ON "WadReportPhoto" ("ReportId", "RequestId");
COMMIT;
