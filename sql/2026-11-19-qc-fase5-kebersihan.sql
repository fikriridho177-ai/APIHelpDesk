-- QC Module — Fase 5: Kebersihan Bulanan Nenas (detail typed + view hitungan)
--                     + master Penyesuaian Populasi (CRUD lokal).
-- Target database : helpdeskasd (PostgreSQL). Jalankan MANUAL setelah review.
-- Idempotent: CREATE TABLE/INDEX IF NOT EXISTS, CREATE OR REPLACE VIEW,
--             INSERT menu ON CONFLICT-safe, UPDATE aktivasi form.
-- Script ini TANPA BEGIN/COMMIT internal supaya bisa dibungkus transaksi uji.
-- Rollback: 2026-11-19-qc-fase5-kebersihan-rollback.sql
--
-- Angka MENTAH saja di tabel (jumlah tanaman/jalur, luas, 5 bucket gulma).
-- Umur tanam, SPH, Bersih/Kotor (ha & %) dihitung di view PostgreSQL — tidak
-- disimpan. Rumus取自 template asli "Kondisi Kebersihan Kebun Nanas (Oktober 2026).xls"
-- (lihat docs/qc/05-kebersihan-bulanan-penyesuaian.md):
--   UmurTanam   = DATEDIF(BulanTanam, TODAY(), "M")  -> bulan penuh berjalan
--   SPH         = JumlahTanaman / LuasHa             (NULL bila LuasHa = 0)
--   BersihHa    = Gulma0to5Ha                        (bucket 0–<5 = standar/bersih)
--   KotorHa     = Gulma5to10Ha + Gulma10to25Ha + Gulma25to50Ha + GulmaOver50Ha
--   JumlahHa    = BersihHa + KotorHa
--   PersenBersih= BersihHa / JumlahHa * 100          (NULL bila JumlahHa = 0)
--   PersenKotor = KotorHa  / JumlahHa * 100          (NULL bila JumlahHa = 0)
-- Legenda asli: 0–<5 = A (Standar/Bersih); 5–<25 = B; 25–<50 = C; >50 = D (Kotor).
--
-- Satu inspeksi kebersihan = satu periode (tahun/bulan) mencakup banyak persil
-- (maks 200 baris sesuai sheet asli). Periode di-snapshot ke baris detail agar
-- unik global (PeriodYear, PeriodMonth, PersilKode): satu persil satu baris per
-- periode, mencegah double counting antar inspeksi/revisi.

-- =========================================================
-- 1. MstQcPenyesuaianPopulasi — master penyesuaian populasi (CRUD lokal)
--    Referensi dokumen pengurangan/penambahan pohon per persil, mis.
--    "003/BRA/WIL.2/01/2026 (PENGURANGAN POHON)". Baris kebersihan menautkan
--    master ini (FK SET NULL) + snapshot NoPenyesuaian agar histori tetap terbaca.
--    Tidak ada aritmetika populasi tersimpan; JumlahTanaman tetap angka mentah.
-- =========================================================
CREATE TABLE IF NOT EXISTS "MstQcPenyesuaianPopulasi" (
    "Id"           serial       PRIMARY KEY,
    "NoReferensi"  varchar(100) NOT NULL,
    "Tanggal"      date         NOT NULL,
    "PersilKode"   varchar(100) NULL,
    "WilayahKode"  varchar(50)  NULL,
    "Jenis"        varchar(20)  NOT NULL,   -- PENGURANGAN / PENAMBAHAN
    "JumlahPohon"  int          NOT NULL DEFAULT 0,
    "Keterangan"   varchar(300) NULL,
    "Active"       boolean      NOT NULL DEFAULT true,
    "CreatedBy"    varchar(100) NULL,
    "CreatedAt"    timestamptz  NOT NULL DEFAULT now(),
    "UpdatedBy"    varchar(100) NULL,
    "UpdatedAt"    timestamptz  NULL,
    CONSTRAINT "CK_MstQcPenyesuaianPopulasi_Jenis" CHECK ("Jenis" IN ('PENGURANGAN','PENAMBAHAN')),
    CONSTRAINT "CK_MstQcPenyesuaianPopulasi_JumlahPohon" CHECK ("JumlahPohon" >= 0)
);

CREATE INDEX IF NOT EXISTS "IX_MstQcPenyesuaianPopulasi_NoReferensi"
    ON "MstQcPenyesuaianPopulasi" ("NoReferensi");
CREATE INDEX IF NOT EXISTS "IX_MstQcPenyesuaianPopulasi_PersilKode"
    ON "MstQcPenyesuaianPopulasi" ("PersilKode");
CREATE INDEX IF NOT EXISTS "IX_MstQcPenyesuaianPopulasi_WilayahKode_Active"
    ON "MstQcPenyesuaianPopulasi" ("WilayahKode", "Active");

-- =========================================================
-- 2. TrnQcKebersihanBulanan — satu baris per persil per periode
--    Kapasitas 200 baris sesuai sheet asli (Sheet2 A1:AC233).
-- =========================================================
CREATE TABLE IF NOT EXISTS "TrnQcKebersihanBulanan" (
    "Id"                    bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "InspectionId"          bigint        NOT NULL,
    "RowNo"                 int           NOT NULL,
    "PeriodYear"            int           NOT NULL,
    "PeriodMonth"           int           NOT NULL,
    "PersilKode"            varchar(100)  NOT NULL,
    "WilayahKode"           varchar(50)   NULL,
    "Divisi"                varchar(50)   NULL,
    "Kcb"                   varchar(50)   NULL,
    "BulanTanam"            date          NOT NULL,
    "JumlahTanaman"         int           NOT NULL DEFAULT 0,
    "JumlahJalur"           int           NOT NULL DEFAULT 0,
    "LuasHa"                numeric(12,3) NOT NULL DEFAULT 0,
    "Gulma0to5Ha"           numeric(12,3) NOT NULL DEFAULT 0,
    "Gulma5to10Ha"          numeric(12,3) NOT NULL DEFAULT 0,
    "Gulma10to25Ha"         numeric(12,3) NOT NULL DEFAULT 0,
    "Gulma25to50Ha"         numeric(12,3) NOT NULL DEFAULT 0,
    "GulmaOver50Ha"         numeric(12,3) NOT NULL DEFAULT 0,
    "Grade"                 varchar(32)   NULL,
    "WarnaDaun"             varchar(32)   NULL,
    "KondisiVisual"         varchar(32)   NULL,
    "PenyesuaianPopulasiId" int           NULL,
    "NoPenyesuaian"         varchar(200)  NULL,
    "Keterangan"            varchar(250)  NULL,
    "CreatedAt"             timestamptz   NOT NULL DEFAULT now(),
    CONSTRAINT "FK_TrnQcKebersihanBulanan_TrnQcInspection"
        FOREIGN KEY ("InspectionId") REFERENCES "TrnQcInspection" ("Id") ON DELETE CASCADE,
    CONSTRAINT "FK_TrnQcKebersihanBulanan_MstQcPenyesuaianPopulasi"
        FOREIGN KEY ("PenyesuaianPopulasiId") REFERENCES "MstQcPenyesuaianPopulasi" ("Id") ON DELETE SET NULL,
    CONSTRAINT "CK_TrnQcKebersihanBulanan_RowNo" CHECK ("RowNo" BETWEEN 1 AND 200),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_PeriodMonth" CHECK ("PeriodMonth" BETWEEN 1 AND 12),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_PeriodYear" CHECK ("PeriodYear" BETWEEN 2000 AND 2100),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_JumlahTanaman" CHECK ("JumlahTanaman" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_JumlahJalur" CHECK ("JumlahJalur" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_LuasHa" CHECK ("LuasHa" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_Gulma0to5Ha" CHECK ("Gulma0to5Ha" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_Gulma5to10Ha" CHECK ("Gulma5to10Ha" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_Gulma10to25Ha" CHECK ("Gulma10to25Ha" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_Gulma25to50Ha" CHECK ("Gulma25to50Ha" >= 0),
    CONSTRAINT "CK_TrnQcKebersihanBulanan_GulmaOver50Ha" CHECK ("GulmaOver50Ha" >= 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS "IX_TrnQcKebersihanBulanan_InspectionId_RowNo"
    ON "TrnQcKebersihanBulanan" ("InspectionId", "RowNo");
-- Satu persil hanya satu baris per periode (lintas inspeksi/revisi).
CREATE UNIQUE INDEX IF NOT EXISTS "IX_TrnQcKebersihanBulanan_Periode_Persil"
    ON "TrnQcKebersihanBulanan" ("PeriodYear", "PeriodMonth", "PersilKode");
CREATE INDEX IF NOT EXISTS "IX_TrnQcKebersihanBulanan_InspectionId"
    ON "TrnQcKebersihanBulanan" ("InspectionId");
CREATE INDEX IF NOT EXISTS "IX_TrnQcKebersihanBulanan_Periode_Wilayah"
    ON "TrnQcKebersihanBulanan" ("PeriodYear", "PeriodMonth", "WilayahKode");
CREATE INDEX IF NOT EXISTS "IX_TrnQcKebersihanBulanan_PenyesuaianPopulasiId"
    ON "TrnQcKebersihanBulanan" ("PenyesuaianPopulasiId");

-- =========================================================
-- 3. View hitungan per baris (dipakai export & monitoring)
--    Umur tanam = bulan penuh antara BulanTanam dan CURRENT_DATE (DATEDIF "M").
-- =========================================================
CREATE OR REPLACE VIEW "vwQcKebersihanDetail" AS
SELECT
    s."Id",
    s."InspectionId",
    s."RowNo",
    s."PeriodYear",
    s."PeriodMonth",
    s."PersilKode",
    s."WilayahKode",
    s."Divisi",
    s."Kcb",
    s."BulanTanam",
    s."JumlahTanaman",
    s."JumlahJalur",
    s."LuasHa",
    s."Gulma0to5Ha",
    s."Gulma5to10Ha",
    s."Gulma10to25Ha",
    s."Gulma25to50Ha",
    s."GulmaOver50Ha",
    s."Grade",
    s."WarnaDaun",
    s."KondisiVisual",
    s."PenyesuaianPopulasiId",
    s."NoPenyesuaian",
    s."Keterangan",
    (EXTRACT(YEAR FROM age(CURRENT_DATE, s."BulanTanam")) * 12
        + EXTRACT(MONTH FROM age(CURRENT_DATE, s."BulanTanam")))::int AS "UmurTanam",
    CASE WHEN s."LuasHa" > 0
        THEN ROUND(s."JumlahTanaman"::numeric / s."LuasHa", 2)
        ELSE NULL
    END AS "Sph",
    s."Gulma0to5Ha" AS "BersihHa",
    (s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") AS "KotorHa",
    (s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") AS "JumlahHa",
    CASE WHEN (s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") > 0
        THEN ROUND(s."Gulma0to5Ha" * 100
            / (s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 2)
        ELSE NULL
    END AS "PersenBersih",
    CASE WHEN (s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") > 0
        THEN ROUND((s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") * 100
            / (s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 2)
        ELSE NULL
    END AS "PersenKotor",
    i."InspectionNo",
    i."FormId",
    i."InspectionDate",
    i."CompanyId",
    i."CompanyNameSnapshot",
    i."KodeAfdeling",
    i."PersilSumber",
    i."Status",
    i."Revision"
FROM "TrnQcKebersihanBulanan" s
JOIN "TrnQcInspection" i ON i."Id" = s."InspectionId";

-- =========================================================
-- 4. View rekap per inspeksi (footer Total template)
-- =========================================================
CREATE OR REPLACE VIEW "vwQcKebersihanRekap" AS
SELECT
    i."Id" AS "InspectionId",
    i."InspectionNo",
    i."FormId",
    i."InspectionDate",
    i."CompanyId",
    i."CompanyNameSnapshot",
    i."WilayahKode",
    i."KodeAfdeling",
    i."PersilSumber",
    i."PeriodMonth",
    i."PeriodYear",
    i."Status",
    i."Revision",
    COUNT(s."Id")::int AS "JumlahPersil",
    COALESCE(SUM(s."JumlahTanaman"), 0)::int AS "TotalTanaman",
    COALESCE(SUM(s."JumlahJalur"), 0)::int AS "TotalJalur",
    COALESCE(SUM(s."LuasHa"), 0) AS "TotalLuasHa",
    COALESCE(SUM(s."Gulma0to5Ha"), 0) AS "TotalGulma0to5Ha",
    COALESCE(SUM(s."Gulma5to10Ha"), 0) AS "TotalGulma5to10Ha",
    COALESCE(SUM(s."Gulma10to25Ha"), 0) AS "TotalGulma10to25Ha",
    COALESCE(SUM(s."Gulma25to50Ha"), 0) AS "TotalGulma25to50Ha",
    COALESCE(SUM(s."GulmaOver50Ha"), 0) AS "TotalGulmaOver50Ha",
    COALESCE(SUM(s."Gulma0to5Ha"), 0) AS "BersihHa",
    COALESCE(SUM(s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) AS "KotorHa",
    COALESCE(SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) AS "JumlahHa",
    CASE WHEN COALESCE(SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) > 0
        THEN ROUND(SUM(s."Gulma0to5Ha") * 100
            / SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 2)
        ELSE NULL
    END AS "PersenBersih",
    CASE WHEN COALESCE(SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) > 0
        THEN ROUND(SUM(s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") * 100
            / SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 2)
        ELSE NULL
    END AS "PersenKotor"
FROM "TrnQcInspection" i
JOIN "MstQcForm" f ON f."Id" = i."FormId" AND f."Code" = 'QC-KEBERSIHAN-NNS'
LEFT JOIN "TrnQcKebersihanBulanan" s ON s."InspectionId" = i."Id"
GROUP BY i."Id", i."InspectionNo", i."FormId", i."InspectionDate", i."CompanyId",
         i."CompanyNameSnapshot", i."WilayahKode", i."KodeAfdeling", i."PersilSumber",
         i."PeriodMonth", i."PeriodYear", i."Status", i."Revision";

-- =========================================================
-- 5. View rekap per wilayah per periode (chart bersih/kotor GRAFIK asli)
--    Sumber kebenaran chart frontend & export rekap wilayah.
-- =========================================================
CREATE OR REPLACE VIEW "vwQcKebersihanRekapWilayah" AS
SELECT
    s."PeriodYear",
    s."PeriodMonth",
    s."WilayahKode",
    COUNT(s."Id")::int AS "JumlahPersil",
    COALESCE(SUM(s."JumlahTanaman"), 0)::int AS "TotalTanaman",
    COALESCE(SUM(s."LuasHa"), 0) AS "TotalLuasHa",
    COALESCE(SUM(s."Gulma0to5Ha"), 0) AS "BersihHa",
    COALESCE(SUM(s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) AS "KotorHa",
    COALESCE(SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) AS "JumlahHa",
    CASE WHEN COALESCE(SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) > 0
        THEN ROUND(SUM(s."Gulma0to5Ha") * 100
            / SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 2)
        ELSE NULL
    END AS "PersenBersih",
    CASE WHEN COALESCE(SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 0) > 0
        THEN ROUND(SUM(s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha") * 100
            / SUM(s."Gulma0to5Ha" + s."Gulma5to10Ha" + s."Gulma10to25Ha" + s."Gulma25to50Ha" + s."GulmaOver50Ha"), 2)
        ELSE NULL
    END AS "PersenKotor"
FROM "TrnQcKebersihanBulanan" s
GROUP BY s."PeriodYear", s."PeriodMonth", s."WilayahKode";

-- =========================================================
-- 6. Menu QC_KEBERSIHAN (halaman periode + chart) + hak default ADMIN.
-- =========================================================
INSERT INTO "UtlMenu" ("ParentId", "Code", "Name", "Route", "Icon", "Description", "MenuType", "SortOrder", "Active", "CreatedBy", "CreatedAt")
SELECT parent."Id", 'QC_KEBERSIHAN', 'Kebersihan Bulanan', '/qc/kebersihan', 'leaf',
       'Kondisi kebersihan kebun nanas per periode: grid per persil, rekap bersih/kotor per wilayah, dan penyesuaian populasi.',
       'MENU', 9, true, 'system', now()
FROM "UtlMenu" parent
WHERE parent."Code" = 'QC'
  AND NOT EXISTS (SELECT 1 FROM "UtlMenu" m WHERE m."Code" = 'QC_KEBERSIHAN');

INSERT INTO "UtlGroupMenu"
    ("GroupId", "MenuId", "CanView", "CanRead", "CanCreate", "CanUpdate", "CanDelete", "CanApprove", "CanExport")
SELECT g."Id", m."Id", true, true, true, true, true, true, true
FROM "UtlGroup" g
CROSS JOIN "UtlMenu" m
WHERE g."Code" = 'ADMIN'
  AND m."Code" = 'QC_KEBERSIHAN'
  AND NOT EXISTS (
      SELECT 1 FROM "UtlGroupMenu" gm
      WHERE gm."GroupId" = g."Id" AND gm."MenuId" = m."Id"
  );

