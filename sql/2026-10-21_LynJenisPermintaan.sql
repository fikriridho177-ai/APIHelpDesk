-- Master Jenis Permintaan (21 Okt 2026)
-- Jenis permintaan (Pembuatan Peta, Drone Foto Udara, ...) tidak lagi berupa sub-menu, tapi baris di tabel
-- "LynJenisPermintaan" dengan pembeda divisi ("DivisionMenuId" = menu divisi, mis. LYN_GIS).
-- Halaman divisi menampilkan form pengajuan dengan pilihan Jenis Permintaan dari tabel ini.
--
-- Script ini:
--   1. membuat tabel LynJenisPermintaan + kolom LynRequest.JenisId
--   2. menyalin sub-layanan form pengajuan (menu MENU berkode LYN_ di bawah divisi, bukan halaman sensus) menjadi jenis
--   3. menggabungkan hak akses sub-layanan tsb ke menu divisinya (hak akses tidak berkurang)
--   4. memindahkan tiket lama: MenuId -> menu divisi, JenisId -> jenis
--   5. menonaktifkan sub-menu yang sudah jadi jenis (bisa diaktifkan lagi di Manajemen Menu)
--   6. menambah menu halaman Approval / Monitoring / Analisis / Master Jenis Permintaan di bawah Layanan
--
-- Jalankan SEKALI di database HelpDesk (PostgreSQL), SEBELUM restart API. Aman bila tidak sengaja dijalankan ulang.

BEGIN;

-- 1. Tabel master & kolom tiket ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "LynJenisPermintaan" (
    "Id"             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "DivisionMenuId" integer      NOT NULL REFERENCES "UtlMenu" ("Id"),
    "Code"           varchar(50)  NOT NULL,
    "Name"           varchar(150) NOT NULL,
    "Description"    varchar(500) NULL,
    "IsOther"        boolean      NOT NULL DEFAULT false,
    "SortOrder"      integer      NOT NULL DEFAULT 0,
    "Active"         boolean      NOT NULL DEFAULT true,
    "CreatedAt"      timestamptz  NOT NULL DEFAULT now(),
    "UpdatedAt"      timestamptz  NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS "UX_LynJenisPermintaan_Code" ON "LynJenisPermintaan" ("Code");
CREATE INDEX IF NOT EXISTS "IX_LynJenisPermintaan_DivisionMenuId" ON "LynJenisPermintaan" ("DivisionMenuId");

ALTER TABLE "LynRequest" ADD COLUMN IF NOT EXISTS "JenisId" integer NULL REFERENCES "LynJenisPermintaan" ("Id");
CREATE INDEX IF NOT EXISTS "IX_LynRequest_JenisId" ON "LynRequest" ("JenisId");

-- Sub-layanan yang dijadikan jenis: menu MENU berkode LYN_ tepat di bawah divisi (GROUP LYN_ di bawah LAYANAN),
-- kecuali halaman sensus (kodenya dipakai di MstHpt.MenuCode).
CREATE TEMP TABLE tmp_jenis_menu ON COMMIT DROP AS
SELECT m."Id" AS "MenuId", m."ParentId" AS "DivisionMenuId", m."Code", m."Name", m."Description", m."SortOrder", m."Active"
FROM "UtlMenu" m
JOIN "UtlMenu" d ON d."Id" = m."ParentId" AND d."MenuType" = 'GROUP' AND d."Code" LIKE 'LYN\_%'
JOIN "UtlMenu" r ON r."Id" = d."ParentId" AND r."Code" = 'LAYANAN'
WHERE m."MenuType" = 'MENU'
  AND m."Code" LIKE 'LYN\_%'
  AND NOT EXISTS (SELECT 1 FROM "MstHpt" h WHERE h."MenuCode" = m."Code");

-- 2. Salin sub-layanan menjadi jenis permintaan --------------------------------------------------
INSERT INTO "LynJenisPermintaan" ("DivisionMenuId", "Code", "Name", "Description", "IsOther", "SortOrder", "Active")
SELECT t."DivisionMenuId", t."Code", t."Name", LEFT(t."Description", 500), t."Code" LIKE '%\_LAINNYA', t."SortOrder", t."Active"
FROM tmp_jenis_menu t
ON CONFLICT ("Code") DO NOTHING;

-- 3. Hak akses sub-layanan (yang masih aktif) digabung ke menu divisinya --------------------------
CREATE TEMP TABLE tmp_jenis_rights ON COMMIT DROP AS
SELECT gm."GroupId", t."DivisionMenuId",
       bool_or(gm."CanView") AS v, bool_or(gm."CanRead") AS r, bool_or(gm."CanCreate") AS c, bool_or(gm."CanUpdate") AS u,
       bool_or(gm."CanDelete") AS d, bool_or(gm."CanApprove") AS a, bool_or(gm."CanExport") AS e
FROM "UtlGroupMenu" gm
JOIN tmp_jenis_menu t ON t."MenuId" = gm."MenuId" AND t."Active"
GROUP BY gm."GroupId", t."DivisionMenuId";

UPDATE "UtlGroupMenu" gd
SET "CanView" = gd."CanView" OR s.v, "CanRead" = gd."CanRead" OR s.r, "CanCreate" = gd."CanCreate" OR s.c,
    "CanUpdate" = gd."CanUpdate" OR s.u, "CanDelete" = gd."CanDelete" OR s.d, "CanApprove" = gd."CanApprove" OR s.a,
    "CanExport" = gd."CanExport" OR s.e
FROM tmp_jenis_rights s
WHERE gd."GroupId" = s."GroupId" AND gd."MenuId" = s."DivisionMenuId";

INSERT INTO "UtlGroupMenu" ("GroupId", "MenuId", "CanView", "CanRead", "CanCreate", "CanUpdate", "CanDelete", "CanApprove", "CanExport")
SELECT s."GroupId", s."DivisionMenuId", s.v, s.r, s.c, s.u, s.d, s.a, s.e
FROM tmp_jenis_rights s
WHERE NOT EXISTS (SELECT 1 FROM "UtlGroupMenu" gm WHERE gm."GroupId" = s."GroupId" AND gm."MenuId" = s."DivisionMenuId");

-- 4. Tiket lama pindah ke divisi + jenisnya ------------------------------------------------------
UPDATE "LynRequest" q
SET "JenisId" = j."Id", "MenuId" = j."DivisionMenuId"
FROM tmp_jenis_menu t
JOIN "LynJenisPermintaan" j ON j."Code" = t."Code"
WHERE q."MenuId" = t."MenuId";

-- 5. Sub-menu yang sudah jadi jenis dinonaktifkan (kartu per sub-layanan tidak tampil lagi) -------
UPDATE "UtlMenu"
SET "Active" = false, "UpdatedBy" = 'system', "UpdatedAt" = now()
WHERE "Id" IN (SELECT "MenuId" FROM tmp_jenis_menu WHERE "Active");

-- 6. Halaman Approval / Monitoring / Analisis / Master Jenis di bawah menu Layanan ----------------
INSERT INTO "UtlMenu" ("ParentId", "Code", "Name", "Route", "Icon", "Description", "MenuType", "SortOrder", "Active", "CreatedBy", "CreatedAt")
SELECT p."Id", v.code, v.name, v.route, v.icon, v.description, 'MENU', v.sort_order, true, 'system', now()
FROM (SELECT "Id" FROM "UtlMenu" WHERE "Code" = 'LAYANAN') AS p
CROSS JOIN (VALUES
    ('PMT_APPROVAL',     'Approval Permintaan',     '/permintaan/approval',     'check',    70, 'Tiket baru yang menunggu approval.'),
    ('PMT_MONITORING',   'Monitoring Permintaan',   '/permintaan/monitoring',   'chart',    71, 'Status & antrian tiket semua divisi, export Excel / PDF.'),
    ('PMT_ANALISIS',     'Analisis Permintaan',     '/permintaan/analisis',     'chart',    72, 'Kinerja per divisi & jenis: waktu selesai, ketepatan deadline.'),
    ('PMT_MASTER_JENIS', 'Master Jenis Permintaan', '/permintaan/master-jenis', 'settings', 73, 'Daftar jenis permintaan per divisi untuk form pengajuan.')
) AS v(code, name, route, icon, sort_order, description)
WHERE NOT EXISTS (SELECT 1 FROM "UtlMenu" m WHERE m."Code" = v.code);

-- Hak default (hanya menambah baris yang belum ada), berdasarkan hak group di menu divisi:
--   Approval        : group yang punya Approve di salah satu divisi
--   Monitoring/Anls : group petugas (Read / Approve / Update) di salah satu divisi; Export ikut hak Export divisi
--   Master Jenis    : group yang punya Update / Approve di salah satu divisi
CREATE TEMP TABLE tmp_division_rights ON COMMIT DROP AS
SELECT gm."GroupId",
       bool_or(gm."CanApprove") AS a,
       bool_or(gm."CanRead" OR gm."CanApprove" OR gm."CanUpdate") AS handler,
       bool_or(gm."CanUpdate" OR gm."CanApprove") AS manage,
       bool_or(gm."CanExport") AS e
FROM "UtlGroupMenu" gm
JOIN "UtlMenu" d ON d."Id" = gm."MenuId" AND d."MenuType" = 'GROUP' AND d."Code" LIKE 'LYN\_%'
JOIN "UtlMenu" r ON r."Id" = d."ParentId" AND r."Code" = 'LAYANAN'
GROUP BY gm."GroupId";

INSERT INTO "UtlGroupMenu" ("GroupId", "MenuId", "CanView", "CanRead", "CanCreate", "CanUpdate", "CanDelete", "CanApprove", "CanExport")
SELECT s."GroupId", m."Id",
       true, true,
       m."Code" = 'PMT_MASTER_JENIS', m."Code" = 'PMT_MASTER_JENIS', m."Code" = 'PMT_MASTER_JENIS',
       m."Code" = 'PMT_APPROVAL',
       m."Code" IN ('PMT_MONITORING', 'PMT_ANALISIS') AND s.e
FROM tmp_division_rights s
JOIN "UtlMenu" m ON m."Code" IN ('PMT_APPROVAL', 'PMT_MONITORING', 'PMT_ANALISIS', 'PMT_MASTER_JENIS')
WHERE ((m."Code" = 'PMT_APPROVAL' AND s.a)
    OR (m."Code" IN ('PMT_MONITORING', 'PMT_ANALISIS') AND s.handler)
    OR (m."Code" = 'PMT_MASTER_JENIS' AND s.manage))
  AND NOT EXISTS (SELECT 1 FROM "UtlGroupMenu" gm WHERE gm."GroupId" = s."GroupId" AND gm."MenuId" = m."Id");

COMMIT;

